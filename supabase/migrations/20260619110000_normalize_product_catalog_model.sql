alter table public.products
  add column display_name text,
  add column stock_units numeric(12,3),
  add column units_per_case integer,
  add column category_id bigint references public.catalog_categories(id);

update public.products p
set display_name = coalesce(cp.display_name, p.article_name),
    units_per_case = case
      when cp.units_label ~ '^\s*\d+' then
        (substring(cp.units_label from '^\s*(\d+)'))::integer
      else null
    end,
    category_id = c.id
from public.catalog_products cp,
     public.catalog_categories c
where cp.product_id = p.id
  and c.display_name = cp.category;

alter table public.products
  alter column display_name set not null,
  alter column category_id set not null;

alter table public.catalog_products
  add column catalog_id uuid references public.catalogs(id);

update public.catalog_products
