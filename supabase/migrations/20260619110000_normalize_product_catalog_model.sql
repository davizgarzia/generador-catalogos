alter table public.catalog_products
  drop column display_name,
  drop column units_label,
  drop column category;

alter table public.products
  drop column units,
  drop column family_name;

create index products_category_id_idx
  on public.products (category_id);

create index catalog_products_product_id_idx
  on public.catalog_products (product_id);

create index catalog_products_catalog_sort_order_idx
  on public.catalog_products (catalog_id, sort_order);

alter table public.catalog_categories enable row level security;
alter table public.catalogs enable row level security;

create policy "catalog categories are publicly readable"
  on public.catalog_categories for select
  to anon, authenticated
  using (active = true);

create policy "active catalogs are publicly readable"
  on public.catalogs for select
  to anon, authenticated
  using (active = true);

create policy "catalog admins manage categories"
  on public.catalog_categories for all
  to authenticated
  using (
    exists (
      select 1 from public.catalog_admins
      where user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public.catalog_admins
      where user_id = auth.uid()
    )
  );

create policy "catalog admins manage catalogs"
  on public.catalogs for all
  to authenticated
  using (
    exists (
      select 1 from public.catalog_admins
      where user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public.catalog_admins
      where user_id = auth.uid()
    )
  );
